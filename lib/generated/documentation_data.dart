    '## 5. Development Guidelines\n'
    '\n'
    '### 5.1 Code Style & Conventions\n'
    '\n'
    '**Python (MacRemote):**\n'
    '- Follow PEP 8.\n'
    '- Use type hints for all function signatures.\n'
    '- Use Pydantic v2 models for request/response validation.\n'
    '- Prefer async/await for I/O-bound operations.\n'
    '- Use `pathlib.Path` for filesystem paths.\n'
    '- Log via `logging.getLogger("macremote")`.\n'
    '\n'
    '**Dart/Flutter (OpenGate):**\n'
    '- Follow the [Dart style guide](https://dart.dev/guides/language/effective-dart/style).\n'
    '- Use `const` constructors where possible.\n'
    '- Prefer `super.key` for widget keys.\n'
    '- Use `=>` for short getters and methods.\n'
    '- Organize imports: Flutter SDK → third-party packages → project packages.\n'
    '- Use named constructors for clarity.\n'
    '\n'
    '### 5.2 Flutter Design Language\n'
    '\n'
    'When building new screens, follow these established patterns:\n'
    '\n'
    '| Property | Value |\n'
    '|---|---|\n'
    '| **Font** | Google Sans (custom font in `assets/fonts/`) |\n'
    '| **Spacing grid** | 8 px base unit. Paddings use multiples of 8 |\n'
    '| **Border radius** | Cards/containers: 12 px. Dialogs: 16 px |\n'
    '| **Card style** | Outlined containers (`Border.all(color: outline)`) with no elevation |\n'
    '| **Card background** | Transparent or `colorScheme.surface` |\n'
    '| **AppBar** | `centerTitle: false`, `elevation: 0`, `scrolledUnderElevation: 0`, `titleSpacing: 0` |\n'
    '| **Primary color** | Light: black. Dark: white |\n'
    '| **Accent color** | `#469AF9` (70, 154, 249) |\n'
    '| **Theme mode** | `ThemeMode.system` (adapts to system light/dark) |\n'
    '| **Navigation** | `Navigator.push(MaterialPageRoute(...))` |\n'
    '| **Home screen nav** | `_InstantPageRoute` (zero-duration transition for provider cards) |\n'
    '| **Icons** | Material Icons + Cupertino Icons + SVG provider icons |\n'
    '\n'
    '**Key theming file:** `lib/app/theme/app_theme.dart` contains `AppTheme.light()` and `AppTheme.dark()` ThemeData factories used by `MyApp`.\n'
    '\n'
    '### 5.3 State Management Policy\n'
    '\n'
    '**NO third-party state management packages.** Only Flutter built-in state management is permitted.\n'
    '\n'
    '| Pattern | When to Use |\n'
    '|---|---|\n'
    '| `StatefulWidget` + `setState` | Local UI state (form fields, loading flags, toggles, expand/collapse) |\n'
    '| `ValueNotifier<T>` | Observable singleton state (e.g., `MacCompanionService.stateNotifier`), consumed with `ValueListenableBuilder` |\n'
    '| `ChangeNotifier` | Service singletons that need to notify multiple listening widgets |\n'
    '| `FutureBuilder` | One-shot async data loading (API calls, settings load, package info) |\n'
    '| `StreamBuilder` | Streaming data (chat SSE responses, WebSocket events, progress polling) |\n'
    '\n'
    '**Banned packages:** `provider`, `riverpod`, `flutter_bloc`, `bloc`, `get`, `getx`, `mobx`, `rxdart`, or any other third-party state management library.\n'
    '\n'
    '**Service pattern:** All service singletons use:\n'
    '```dart\n'
    'class MyService {\n'
    '  static final MyService instance = MyService._();\n'
    '  MyService._();\n'
    '  // ... async init should be lazy or explicit init() call\n'
    '}\n'
    '```\n'
    '\n'
    '### 5.4 Backend Patterns\n'
    '\n'
    '- **Configuration:** All settings come from environment variables loaded via `python-dotenv` in `config.py`.\n'
    '- **Error handling:** Return structured JSON errors with appropriate HTTP status codes.\n'
    '- **Audit logging:** Every HTTP request is logged to the audit database for traceability.\n'
    '- **Approval:** Sensitive commands require human approval unless session is in `full_access` mode.\n'
    '- **Filesystem scope:** Filesystem operations accept explicit macOS paths across the filesystem. Delete operations still refuse protected system paths.\n'
    '- **Protected paths:** System paths (`/System`, `/Applications`, `/bin`, etc.) can never be deleted.\n'
    '\n'
    '### 5.5 Testing\n'
    '\n'
    '**Backend (MacRemote):**\n'
    '```bash\n'
    'cd MacRemote\n'
    'source .venv/bin/activate\n'
    'pytest\n'
    '```\n'
    'Tests cover terminal execution, command approval logic, GUI routes, media capture, and WebSocket protocol.\n'
    '\n'
    '**Frontend (OpenGate):**\n'
    '```bash\n'
    'cd OpenGate\n'
    'flutter test\n'
    '```\n'
