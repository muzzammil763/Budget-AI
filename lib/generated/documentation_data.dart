    '## 4. Agent Integration\n'
    '\n'
    '### 4.1 Supported Agents\n'
    '\n'
    'MacRemote can launch five AI coding agents as background processes through its backend API. OpenGate\'s chat tool catalog no longer exposes separate delegation tools for these agents; agent launch remains a backend API capability.\n'
    '\n'
    '| Agent | Endpoint | CLI Command | Approval Required |\n'
    '|---|---|---|---|\n'
    '| **Claude Code** | `POST /api/v1/agents/claude` | `claude --dangerously-skip-permissions -p <prompt>` | Yes (sensitive commands) |\n'
    '| **Codex** | `POST /api/v1/agents/codex` | `codex exec --full-auto <prompt>` | Yes |\n'
    '| **CommandCode** | `POST /api/v1/agents/commandcode` | `cmd --yolo --print <prompt>` | Yes |\n'
    '| **Pi** | `POST /api/v1/agents/pi` | `pi --print <prompt>` | Yes |\n'
    '| **OpenCode** | `POST /api/v1/agents/opencode` | `opencode run <prompt>` | Yes |\n'
    '\n'
    '### 4.2 How Agents Interact with the System\n'
    '\n'
    '1. **Agent launch:** The system/chat sends a request to the appropriate agent endpoint with a prompt and optional working directory.\n'
    '2. **Background execution:** The agent CLI runs as a background subprocess. The endpoint returns a `command_id` immediately.\n'
    '3. **Progress polling:** The caller polls `GET /api/v1/terminal/progress/{command_id}` to get live stdout/stderr, elapsed time, and completion status.\n'
    '4. **WebSocket push:** When available, agents push progress updates via the WebSocket connection (task_update events).\n'
    '5. **Result:** When the agent completes, the final output (stdout + stderr) is available through the progress endpoint.\n'
    '\n'
    '### 4.3 Approval Flow\n'
    '\n'
    'Every command executed through the terminal endpoint can pass through the approval system:\n'
    '\n'
    '```\n'
    '1. User/Agent sends command to POST /terminal/execute\n'
    '2. Server checks current permission mode for the session\n'
    '3. If mode = "default" and command matches sensitive patterns:\n'
    '   → Command is held; approval request emitted via WebSocket\n'
    '   → OpenGate shows an approval dialog\n'
    '   → User approves/denies via POST /api/v1/approval/respond\n'
    '   → If approved, command executes and can be allowlisted for the session\n'
    '4. If mode = "full_access":\n'
    '   → Command executes immediately without human intervention\n'
    '```\n'
    '\n'
    '**Sensitive command patterns** (triggers approval gate): `sudo`, `rm`, `dd of=`, `mkfs`, `diskutil erase/partition`, `chmod -R 777`, `chown -R`.\n'
    '\n'
