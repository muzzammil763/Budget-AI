    '**Key architecture decisions:**\n'
    '\n'
    '- **No third-party state management** — exclusively uses `StatefulWidget` + `setState`, `ValueNotifier`, `ChangeNotifier`, `FutureBuilder`, and `StreamBuilder`.\n'
    '- **Service singletons** — database-backed services (Memory, Reminder, Finance) and connection services (MacCompanion) use singleton patterns with `instance` getters.\n'
    '- **Unified chat architecture** — all 12 AI providers share a single `UnifiedChatScreen` widget, parameterized by `ChatModelConfig`. Each provider defines its own base URL, API key slot, model list, and feature flags. OpenGate syncs supported provider catalogs from models.dev, including Anthropic Claude (`anthropic`), DeepSeek (`deepseek`), Fireworks AI (`fireworks-ai`), and Firepass (`firepass`).\n'
    '- **Voice chat layer** — `UnifiedChatScreen` supports text-to-speech response playback using the device default voice and a speech-to-text voice mode via `flutter_tts` and `speech_to_text`; Android declares `RECORD_AUDIO`.\n'
    '- **Skill discovery** — unified chat can discover reusable local skill instruction packs saved by the app under the device\'s OpenGate data directory. The system prompt lists saved skills by name and description; the AI can call `skill_read` to load full skill instructions when relevant. The Skills screen can create, edit, view, import, export, and delete local skills, and Backup & Restore includes them.\n'
    '- **Tool detail rendering** — agentic tool-call panels render code-shaped arguments and results with `ThemedCodeBlock`, including streaming write content. Expanded edit replacement details use natural height without an inner capped scroll area.\n'
    '- **Streaming haptics** — every visible response text chunk triggers subtle `selectionClick` haptics while the chat screen is foregrounded and Settings → Haptics is enabled, including intermediate agentic response text before the final answer.\n'
    '- **Context snapshots** — when memory and finance tools are enabled, unified chat injects saved memories plus a compact finance snapshot with today\'s total, current-month total, and the full current-month category breakdown.\n'
    '- **Context usage display** — unified chat shows the latest provider-reported prompt/context tokens in the input actions and context sheet; the indicator turns red at 80% usage or over limit. Manual and automatic chat compaction are not available.\n'
    '- **Provider history hygiene** — reasoning/thinking text is rendered in the UI but is not sent back in provider tool-call history unless the provider protocol requires it, such as DeepSeek reasoning mode with tool calls. This keeps later turns focused on user-visible answers and tool results while preserving provider compatibility.\n'
    '- **Remote media and file cache** — MacRemote screenshots, screen recordings, camera captures, audio recordings, and sent files are downloaded through an app-managed persistent cache under app documents. Reopened chats reuse cached files instead of re-downloading them, and Cache Manager can preview images/videos/audio/code, install cached APKs, and manually delete cached files. Chat context contains only file metadata/URLs/tool results, not the file bytes.\n'
    '- **Response flow inspection** — assistant response actions can open a zoomable `AgentResponseFlowScreen` for that specific turn, with expandable nodes for the user message, system prompt snapshot, exposed reasoning, tool calls, tool results, and final reply.\n'
    '- **Android lifecycle streaming** — unified chat starts a native foreground service while an agent response is active, exposes Background Agent readiness in Permissions, pauses reachability polling while Android backgrounds the app, suppresses transient no-internet UI briefly on resume, preserves partial reasoning/tool-process blocks across stream retries, and automatically continues recoverable edit failures plus backend file-access failures using tool results as retry context.\n'
    '- **Repository tool routing** — remote Mac projects use MacRemote bash with native `git` and `gh` commands for repo actions. The chat composer GitHub button toggles local GitHub mode on or off for subsequent messages; when enabled, local GitHub tools use the user\'s GitHub PAT and app-storage clones without requiring MacRemote.\n'
    '- **Remote working directory fallback** — MacRemote terminal commands without an explicit `working_directory` run in `MACREMOTE_WORKSPACE_ROOT` (default `~/.remoteAgent/projects`). OpenGate remembers the latest remote bash working directory, including common `cd project && ...` and `git -C project ...` project-root hints, and uses it for follow-up relative `read`, `write`, and `edit` tool paths.\n'
    '- **Backend Capability Dashboard** — `BackendHomeScreen` shows a compact operational dashboard above the backend tiles: MacRemote reachability, approval mode, Full Disk Access status, WhatsApp readiness/scheduled count, active backend command count, and the latest connection/error note.\n'
    '- **Backend Terminal screen** — `TerminalScreen` provides direct MacRemote shell access from OpenGate with multiple terminal sessions, per-session history and working directories, practical `cd`/`cd ..`/`cd -` navigation, background command polling so the input stays usable, approval prompts for sensitive commands, and theme-aware light/dark styling.\n'
    '- **Backend WhatsApp screen and tools** — `WhatsAppScreen` plus remote WhatsApp tool modules use MacRemote\'s `wacli` service for setup status, diagnostics, one-shot sync, text/file/poll/reaction/sticker/voice/status/selection sends, scheduled messages, recurring reminders (daily/weekly/hourly/weekdays/custom), chat/group/message/poll listing, contact/message search, message context, media downloads, poll voting, chat state changes, mark-read/unread, delete, edit, forward, revoke, and multi-send workflows.\n'
    '- **SQLite-first local storage** — chat history, memories, reminders, and finances all backed by `sqflite`.\n'
    '- **Shared preferences storage** — provider API keys, GitHub session cache, MacRemote connection details, Home grid column count, configured-provider filtering, haptics, and UI preferences are stored through `SharedPrefsService`. Backend → Connection supports saving partial MacRemote details (host, port, or API key independently), while connection testing still requires all three.\n'
    '- **OpenGate logs** — app logs are written to `~/.remoteAgent/logs` when a home directory is available, with app documents as the fallback.\n'
